#Requires -Version 7
<#
.SYNOPSIS
  Builds the Skrivli release ZIP and its SHA-256 from target\release\skrivli.exe.
.PARAMETER Version
  Release version, X.Y.Z.
.PARAMETER AllowMissingThirdParty
  Local testing only: write a placeholder releases\licenses\THIRD-PARTY.txt when the
  generated one (cargo about, run by CI) is absent.
#>
param(
    [Parameter(Mandatory)][string]$Version,
    [switch]$AllowMissingThirdParty
)

$ErrorActionPreference = 'Stop'

function Get-ExpectedEntries([string]$Root) {
    @(
        "$Root/skrivli.exe",
        "$Root/README.txt",
        "$Root/PRIVACY.txt",
        "$Root/LICENSE.txt",
        "$Root/licenses/sonora-BSD-3-Clause.txt",
        "$Root/licenses/parakeet.cpp-MIT.txt",
        "$Root/licenses/parakeet-tdt-0.6b-v3-CC-BY-4.0.txt",
        "$Root/licenses/nemotron-3.5-asr-OpenMDW-1.1.txt",
        "$Root/licenses/THIRD-PARTY.txt"
    )
}

# Throws if the ZIP lacks an expected entry or holds a *.bin, *.gguf or *.pdb.
function Test-PackageZip([string]$ZipPath, [string]$Root) {
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    $zip = [System.IO.Compression.ZipFile]::OpenRead($ZipPath)
    try {
        $names = @($zip.Entries | ForEach-Object { $_.FullName.Replace('\', '/') })
    }
    finally {
        $zip.Dispose()
    }
    $missing = @(Get-ExpectedEntries $Root | Where-Object { $names -notcontains $_ })
    if ($missing) {
        throw "ZIP is missing expected entries: $($missing -join ', ')"
    }
    $forbidden = @($names | Where-Object { $_ -match '\.(bin|gguf|pdb)$' })
    if ($forbidden) {
        throw "ZIP contains forbidden files: $($forbidden -join ', ')"
    }
}

function Invoke-Package {
    if ($Version -notmatch '^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$') {
        throw "Invalid -Version '$Version': expected X.Y.Z (digits only)."
    }

    $repo = Split-Path -Parent $PSScriptRoot
    Set-Location $repo

    $exe = Join-Path $repo 'target\release\skrivli.exe'
    if (-not (Test-Path -LiteralPath $exe -PathType Leaf)) {
        throw "Missing $exe. Run 'cargo build --release' first."
    }

    # Signing hook (release plan section 8).
    if ($env:SKRIVLI_SIGN_CMD) {
        Write-Host "Signing $exe"
        & $env:SKRIVLI_SIGN_CMD $exe
        if ($LASTEXITCODE) { throw "Signing command failed with exit code $LASTEXITCODE." }
    }

    $thirdParty = Join-Path $repo 'releases\licenses\THIRD-PARTY.txt'
    $placeholder = $false
    if (-not (Test-Path -LiteralPath $thirdParty -PathType Leaf)) {
        if (-not $AllowMissingThirdParty) {
            throw "Missing releases\licenses\THIRD-PARTY.txt. It is generated by CI with 'cargo about'; generate it first (or pass -AllowMissingThirdParty for local tests)."
        }
        $placeholder = $true
    }

    # (source, path inside the package) pairs.
    $files = @(
        @($exe, 'skrivli.exe'),
        @('releases\dist\README.txt', 'README.txt'),
        @('releases\dist\PRIVACY.txt', 'PRIVACY.txt'),
        @('LICENSE', 'LICENSE.txt'),
        @('releases\licenses\sonora-BSD-3-Clause.txt', 'licenses\sonora-BSD-3-Clause.txt'),
        @('releases\licenses\parakeet.cpp-MIT.txt', 'licenses\parakeet.cpp-MIT.txt'),
        @('releases\licenses\parakeet-tdt-0.6b-v3-CC-BY-4.0.txt', 'licenses\parakeet-tdt-0.6b-v3-CC-BY-4.0.txt'),
        @('releases\licenses\nemotron-3.5-asr-OpenMDW-1.1.txt', 'licenses\nemotron-3.5-asr-OpenMDW-1.1.txt')
    )
    if (-not $placeholder) { $files += , @($thirdParty, 'licenses\THIRD-PARTY.txt') }
    foreach ($f in $files) {
        if (-not (Test-Path -LiteralPath $f[0] -PathType Leaf)) {
            throw "Missing required file: $($f[0])"
        }
    }

    $name = "skrivli-$Version-windows-x64"
    $distDir = Join-Path $repo 'target\dist'
    $stage = Join-Path $distDir $name
    $zipPath = Join-Path $distDir "$name.zip"
    $shaPath = "$zipPath.sha256"

    if (Test-Path -LiteralPath $stage) { Remove-Item -LiteralPath $stage -Recurse -Force }
    foreach ($p in $zipPath, $shaPath) {
        if (Test-Path -LiteralPath $p) { Remove-Item -LiteralPath $p -Force }
    }
    New-Item -ItemType Directory -Path (Join-Path $stage 'licenses') -Force | Out-Null

    foreach ($f in $files) {
        Copy-Item -LiteralPath $f[0] -Destination (Join-Path $stage $f[1])
    }
    if ($placeholder) {
        Write-Warning 'Writing placeholder THIRD-PARTY.txt (local test only).'
        [System.IO.File]::WriteAllText(
            (Join-Path $stage 'licenses\THIRD-PARTY.txt'),
            "PLACEHOLDER - not generated by cargo about. Do not release.`n",
            [System.Text.UTF8Encoding]::new($false))
    }

    Add-Type -AssemblyName System.IO.Compression.FileSystem
    [System.IO.Compression.ZipFile]::CreateFromDirectory(
        $stage, $zipPath, [System.IO.Compression.CompressionLevel]::Optimal, $true)

    $hash = (Get-FileHash -LiteralPath $zipPath -Algorithm SHA256).Hash.ToLowerInvariant()
    [System.IO.File]::WriteAllText(
        $shaPath, "$hash  $(Split-Path -Leaf $zipPath)`n", [System.Text.UTF8Encoding]::new($false))

    Test-PackageZip $zipPath $name

    Write-Host "OK: $zipPath"
    Write-Host "    sha256 $hash"
}

# Dot-source guard: tests can load the functions without running a build.
if ($env:SKRIVLI_PACKAGE_NO_RUN -ne '1') { Invoke-Package }
